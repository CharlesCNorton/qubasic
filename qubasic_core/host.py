"""QUBASIC host contract: what the terminal's mixins share, layer by layer,
declared for the type checker.

QBasicTerminal composes Engine and its mixins, which share one set of
instance attributes and call one another's methods through self. Each layer
of the package has a host class declaring what its mixins may use: CoreHost,
then LanguageHost, SimulationHost, ApplicationsHost and PresentationHost,
each extending the one below, and HostState, which holds everything. A mixin
derives from its own layer's host, so mypy rejects a call from one layer into
a layer above it. An attribute is declared at the lowest layer that uses it,
and a method at the layer of the class that defines it first in
QBasicTerminal's MRO. A hook is a method a layer calls and a higher layer
implements; it is declared by hand, with its docstring, in the host of the
lowest layer that calls it. tools/generate.py places the attributes, writes
the method and property stubs and keeps the class docstrings and hooks, and
tests/test_project.py checks the layering and that every stub matches its
definition.
"""

