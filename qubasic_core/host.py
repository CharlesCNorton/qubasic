"""QUBASIC host contract: what the terminal's mixins share, for type checking.

QBasicTerminal composes Engine and its mixins, which read and write one
shared set of instance attributes and call one another's methods. HostState
declares every one of them for the type checker: each attribute with its
type, and each method with the signature of the class that defines it first
in QBasicTerminal's MRO. Every mixin derives from HostState, so mypy holds
each `self.name` to this list and checks every cross-mixin call against the
real signature. A new shared attribute or method is declared here;
tools/sync_host.py rewrites the method stubs from their definitions, and
tests/test_architecture.py checks that the two agree.
"""

